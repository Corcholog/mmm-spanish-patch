"""Read-ahead digest of a script file for the scout agent (docs/TRANSLATION_WORKFLOW.md).

    python -I -X utf8 tools/scout.py digest O0   ->  work/scout/O0_digest.md

A compact overview of a whole script (the Japanese is too long to read in one go):
per 200-entry file the speakers and the first line; time stamps; the most frequent
katakana words, quoted terms ("『...』") and names with honorifics, each with the first
entry where it appears. The scout agent reads this, samples the text, and writes
docs/scouting/<script>.md.
"""
import argparse
import os
import re
import sys
from collections import Counter

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import batch  # noqa: E402
import project  # noqa: E402

KATAKANA = re.compile(r'[ァ-ヶー]{3,}')
QUOTED = re.compile(r'『([^』]{1,16})』')
HONORIFIC = re.compile(r'([^\s「」『』、。！？…⏎]{1,6}?)(さん|くん|君|ちゃん|先輩|先生|様|殿)')
TIME = re.compile(r'(午前|午後)?[０-９0-9]{1,2}時([０-９0-9]{1,2}分)?|[０-９0-9]{1,2}月[０-９0-9]{1,2}日|[月火水木金土日]曜日|翌日|翌朝|その夜')
SPEAKER = re.compile(r'^([^「」\s]{1,12})「')


def top(counter, first, n, min_count=3):
    rows = [(k, c) for k, c in counter.most_common(n * 2) if c >= min_count][:n]
    return '\n'.join(f'- {k} ×{c} (first {first[k]})' for k, c in rows) or '- (none)'


def digest(script):
    entries = [e for e in batch.entries_of(script) if e['ja'].strip()]
    kata, quoted, honor = Counter(), Counter(), Counter()
    first = {}
    out = [f'# Read-ahead digest of {script}: {len(entries)} entries with text\n',
           'Generated by tools/scout.py. Entry IDs are `translation/` IDs.\n',
           '\n## Flow (per translation file of ~200 entries)\n']
    for i in range(0, len(entries), 200):
        chunk = entries[i:i + 200]
        spk = Counter()
        times = []
        for e in chunk:
            m = SPEAKER.match(e['ja'])
            if m:
                spk[m.group(1)] += 1
            t = TIME.search(e['ja'])
            if t:
                times.append(f'{e["id"].split(":")[1]} {t.group(0)}')
            for w in KATAKANA.findall(e['ja']):
                kata[w] += 1
                first.setdefault(w, e['id'])
            for w in QUOTED.findall(e['ja']):
                quoted[w] += 1
                first.setdefault(w, e['id'])
            for name, hon in HONORIFIC.findall(e['ja']):
                honor[name + hon] += 1
                first.setdefault(name + hon, e['id'])
        sample = chunk[0]['ja'][:44]
        sp = ', '.join(f'{k} {v}' for k, v in spk.most_common(5)) or '(narration)'
        out.append(f'- **{chunk[0]["id"]} – {chunk[-1]["id"]}** · speakers: {sp} · starts: 「{sample}」'
                   + (f' · time marks: {"; ".join(times[:6])}' if times else '') + '\n')
    out.append('\n## Most frequent katakana words (names of things, loanwords, sound words)\n')
    out.append(top(kata, first, 120) + '\n')
    out.append('\n## Quoted terms 『…』 (titles, nicknames, emphasised words)\n')
    out.append(top(quoted, first, 60, 2) + '\n')
    out.append('\n## Names with honorifics (how people address each other)\n')
    out.append(top(honor, first, 60, 3) + '\n')
    os.makedirs(os.path.join(project.ROOT, 'work', 'scout'), exist_ok=True)
    path = os.path.join(project.ROOT, 'work', 'scout', f'{script}_digest.md')
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.writelines(out)
    print(path, f'({len("".join(out)):,} characters)')


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest='cmd', required=True)
    p = sub.add_parser('digest')
    p.add_argument('script')
    args = ap.parse_args()
    digest(args.script)


if __name__ == '__main__':
    main()
